def validate_summary_html(project_name):
    """Check if generated Summary HTML contains Draw.io data"""
    print_header("4. Validating Summary HTML Output")
    
    summary_dir = Path(f'projects/{project_name}/outputs/summary')
    
    if not summary_dir.exists():
        print_check(False, f"Summary directory not found: {summary_dir}")
        return False
    
    # Find most recent summary file
    summary_files = list(summary_dir.glob('AVA-FABRIC-SUMMARY-*.html'))
    
    if not summary_files:
        print_check(False, "No summary HTML files found")
        print(f"\n  {Colors.YELLOW}ℹ️  Run: python build_summary_comprehensive.py --project {project_name}{Colors.RESET}")
        return False
    
    latest_file = max(summary_files, key=lambda p: p.stat().st_mtime)
    print_check(True, f"Summary HTML found: {latest_file.name}")
    
    html = latest_file.read_text(encoding='utf-8')
    
    # Check file size (should be ~180KB not 24KB)
    size_kb = len(html) / 1024
    size_ok = size_kb > 100
    print_check(size_ok, f"File size: {size_kb:.1f} KB (expected >100 KB)")
    
    # Check for Draw.io data object
    checks = {
        "drawioFiles object": 'drawioFiles:',
        "renderDrawioViewer function": 'function renderDrawioViewer(',
        "renderAllDrawioViewers call": 'renderAllDrawioViewers();',
        "C4 section": 'id="s-f1-diagrams-c4"',
        "Overall section": 'id="s-f1-diagrams-overall"',
        "BPMN section": 'id="s-f1-diagrams-bpmn"',
        "Sequence section": 'id="s-f1-diagrams-sequence"',
    }
    
    all_passed = True
    for name, marker in checks.items():
        passed = marker in html
        all_passed &= print_check(passed, name)
    
    # Extract drawioFiles data
    match = re.search(r'drawioFiles:\s*(\{[^}]+\})', html)
    if match:
        try:
            # This is a simplified check - actual parsing would be more complex
            drawio_data_snippet = match.group(1)[:100]
            print_check(True, f"drawioFiles data present: {drawio_data_snippet}...")
        except:
            print_check(False, "drawioFiles data malformed")
    else:
        print_check(False, "drawioFiles data not found")
    
    return all_passed and size_ok


