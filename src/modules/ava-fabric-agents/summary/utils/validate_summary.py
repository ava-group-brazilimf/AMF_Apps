def _fix_c1_3(ctx: Ctx) -> Optional[str]:
    """Sweep leftover {{X}} placeholders so the JS stays valid."""
    leftover = sorted(set(re.findall(r'\{\{[A-Z0-9_]+\}\}', ctx.html)))
    if not leftover:
        return None
    h = ctx.html
    for ph in leftover:
        default = '{}' if ph.endswith('_JSON}}') else ''
        h = h.replace(ph, default)
    return h


def _fix_c1_2(ctx: Ctx) -> Optional[str]:
    """Remove a duplicate Mermaid bundle if one was injected twice.
    Heuristic: if `var __esbuild_esm_mermaid` appears more than once, drop the
    second occurrence up to the matching end marker."""
    marker = "var __esbuild_esm_mermaid"
    positions = [m.start() for m in re.finditer(re.escape(marker), ctx.html)]
    if len(positions) <= 1:
        return None
    # Find the <script> boundaries of the duplicates. We keep the first
    # occurrence intact and strip the second <script>…</script> block that
    # contains the marker.
    h = ctx.html
    # Locate the <script> that contains positions[1]
    second = positions[1]
    script_open = h.rfind('<script', 0, second)
    script_close = h.find('</script>', second)
    if script_open < 0 or script_close < 0:
        return None
    # Safety: the <script> should entirely lie after position[0]+500 so we
    # don't accidentally delete the canonical inline library.
    if script_open < positions[0]:
        return None
