# ─────────────────────────────────────────────────────────────────
#  C12.1 — empty_by_failure
# ─────────────────────────────────────────────────────────────────

def _c12da_1(ctx: Ctx) -> Result:
    """C12.1 — No KPI renders 0/N/E/''/\u2014 when its source artifact is
    present and non-trivial (> _EMPTY_THRESHOLD_BYTES bytes).

    Decision tree (plan.md \u00a74.3):
      1. phase.done==False  \u2192 skip (legitimate).
      2. source artifact absent  \u2192 delegate to C12.3 (missing_artifact); skip here.
      3. source artifact \u2264 threshold  \u2192 skip (trivially small; legitimate).
      4. source artifact > threshold + KPI empty  \u2192 HIGH finding.
    """
    kpis: list = ctx.D_kpis or []
    findings: list = []
    skipped_for_c12_3: list = []

    for entry in kpis:
        if not isinstance(entry, dict):
            continue
        k: str = entry.get("k", "")
        v: str = str(entry.get("v", "")).strip()
        if v not in _KPI_EMPTY_VALUES:
            continue

        phase_key = _KPI_PHASE_MAP.get(k, "f1")
        if not _is_phase_done(ctx, phase_key):
            continue  # Legitimate: phase not yet completed

        # Canonical source artifact path per phase
        if phase_key == "f1":
            source = ctx.outputs_dir / "asis" / "metrics.json"
        elif phase_key == "f2":
            source = ctx.outputs_dir / "tobe" / "sizing-report.md"
        else:
            continue  # Unknown mapping — skip

        if not source.exists():
            skipped_for_c12_3.append(k)  # Delegate to C12.3
            continue
        if source.stat().st_size <= _EMPTY_THRESHOLD_BYTES:
            continue  # Trivially small — legitimate empty

        agent_id = PHASE_KEY_MAP.get(phase_key, ["unknown"])[0]
        findings.append({
            "severity": "HIGH",
            "phase": phase_key.upper(),
            "section": f"KPI tile \u2014 {k}",
            "agent_responsible": agent_id,
            "artifact_path": str(source.relative_to(ctx.project_dir)),
            "finding_type": "empty_by_failure",
            "detail": (
                f"KPI '{k}' renders '{v}' while source artifact "
                f"'{source.name}' exists ({source.stat().st_size} bytes > "
                f"{_EMPTY_THRESHOLD_BYTES} B threshold)."
            ),
            "root_cause": (
                "Data-extraction step completed without populating the KPI. "
                "Possible causes: regex mismatch in JS data-injection, empty "
                "metrics file produced by the agent, or template variable not "
                "mapped to the correct D.kpis entry."
            ),
            "auto_correctable": False,
            "suggested_fix": (
                f"Re-run {agent_id} and verify that '{k}' is written "
                "to the JS data block in the generated HTML."
            ),
        })

    if findings:
        detail = (
            f"{len(findings)} KPI(s) empty despite non-trivial source artifact: "
            + ", ".join(f["section"] for f in findings)
        )
        if skipped_for_c12_3:
            detail += f"; {len(skipped_for_c12_3)} delegated to C12.3"
        return Result(False, detail, extra=findings)

    return Result(True, "all non-trivial KPIs populate correctly (or phases incomplete)")


# ─────────────────────────────────────────────────────────────────
#  C12.2 — placeholder_unresolved
# ─────────────────────────────────────────────────────────────────

def _c12da_2(ctx: Ctx) -> Result:
    """C12.2 — No unresolved template placeholder survives in the rendered HTML.

    Regex scope (Op\u00e7\u00e3o C, 2026-08-18):
      \u2022 {{UPPER_VAR}}        \u2014 Jinja2-style tokens
      \u2022 [NEEDS CLARIFICATION] \u2014 editorial marker
      \u2022 AG-\\d+              \u2014 unresolved agent-reference tokens

    INTENTIONALLY EXCLUDED (Op\u00e7\u00e3o C, 2026-08-18 \u2014 prevents double-reporting):
      \u2022 [INCOMPLETE]       \u2192 owned by C11.39 (_c12_1)
      \u2022 [ARTIFACT-MISSING] \u2192 owned by C11.40 (_c12_2)
    Do NOT expand this regex to include those patterns; doing so would cause
    the same finding to appear in both C12.2 and C11.39/C11.40.
    (Op\u00e7\u00e3o C, 2026-08-18)
    """
    # Strip <script> blocks: placeholder tokens inside JS strings are
    # template-internal and must not be flagged.
    html_body = re.sub(
        r'<script[^>]*>.*?</script>', '', ctx.html, flags=re.DOTALL | re.IGNORECASE
    )

    # See deduplication note above \u2014 regex intentionally narrow.
    _PLACEHOLDER_RE = re.compile(
        r'\{\{[A-Z0-9_]+\}\}|\[NEEDS CLARIFICATION\]|AG-\d+'
    )

    matches = _PLACEHOLDER_RE.findall(html_body)
    if not matches:
        return Result(True, "zero unresolved placeholders (post script-strip)")

    unique = sorted(set(matches))

    # Severity: CRITICAL if placeholder is in <title> or <h1> (project identity context)
    critical_re = re.compile(
        r'<(?:title|h1)[^>]*>[^<]*(?:' + '|'.join(re.escape(m) for m in unique) + r')[^<]*</(?:title|h1)>',
        re.IGNORECASE,
    ) if unique else None
    in_critical = bool(critical_re and critical_re.search(ctx.html))
    severity = "CRITICAL" if in_critical else "HIGH"

    findings = [{
        "severity": severity,
        "phase": "UNKNOWN",
        "section": "HTML body (post script-strip)",
        "agent_responsible": "ava-summary",
        "artifact_path": None,
        "finding_type": "placeholder_unresolved",
        "detail": (
            f"{len(matches)} placeholder occurrence(s); "
            f"unique: {', '.join(unique[:8])}{'...' if len(unique) > 8 else ''}"
        ),
        "root_cause": (
            "Template substitution incomplete: one or more Jinja2/AG-ref tokens "
            "were not replaced before HTML emission by build_summary_comprehensive.py."
        ),
        "auto_correctable": True,  # F3 fix (2026-08-18): placeholder_unresolved is auto-correctable per spec §4.5 Success Criteria
        "suggested_fix": (
            "Re-run build_summary_comprehensive.py with complete context data "
            "ensuring all {{}} variables and AG-ref tokens are resolved."
        ),
    }]

    return Result(
        False,
        f"{severity}: {len(matches)} placeholder(s) \u2014 {unique[:4]}{'...' if len(unique) > 4 else ''}",
        extra=findings,
    )


# ─────────────────────────────────────────────────────────────────
#  C12.3 — missing_artifact
# ─────────────────────────────────────────────────────────────────

def _c12da_3(ctx: Ctx) -> Result:
    """C12.3 — All primary_output artifacts in artifact-map.yaml exist for
    completed phases.

    Severity:
      CRITICAL \u2014 primary_output absent for a done phase.
      HIGH     \u2014 non-primary outputs_map artifact absent.
    """
    artifact_map = _load_artifact_map()
    if not artifact_map:
        return Result(True, "artifact-map.yaml not loaded; C12.3 skipped")

    findings: list = []

    for phase_key, agents in artifact_map.items():
        if not isinstance(agents, dict):
            continue
        if not _is_phase_done(ctx, phase_key):
            continue  # Phase not done \u2014 absence is expected

        for agent_id, agent_cfg in agents.items():
            if not isinstance(agent_cfg, dict):
                continue

            primary = agent_cfg.get("primary_output")
            outputs_map: dict = agent_cfg.get("outputs_map") or {}
            html_section = agent_cfg.get("html_section", phase_key.upper())

            candidates: list = []  # (raw_path, is_primary, cfg_dict_or_none)
            if primary:
                candidates.append((primary, True, None))
            for _out_key, out_cfg in outputs_map.items():
                if isinstance(out_cfg, dict):
                    p = out_cfg.get("path")
                    extract_note = out_cfg.get("extract", "") + out_cfg.get("note", "")
                    if p and "glob" not in extract_note:
                        candidates.append((p, False, out_cfg))
                elif isinstance(out_cfg, str):
                    candidates.append((out_cfg, False, None))

            for raw_path, is_primary, cand_cfg in candidates:
                if "{" in raw_path:
                    continue  # Template token — cannot resolve statically
                full_path = (
                    ctx.project_dir / raw_path
                    if not Path(raw_path).is_absolute()
                    else Path(raw_path)
                )
                if full_path.exists():
                    continue
                # Check alternative paths (e.g. CPM XML instead of .md)
                _alt_found = False
                for alt_raw in (cand_cfg.get("alternatives") or [] if isinstance(cand_cfg, dict) else []):
                    alt_path = (
                        ctx.project_dir / alt_raw
                        if not Path(alt_raw).is_absolute()
                        else Path(alt_raw)
                    )
                    if alt_path.exists():
                        _alt_found = True
                        break
                if _alt_found:
                    continue

                sev = "CRITICAL" if is_primary else "HIGH"
                findings.append({
                    "severity": sev,
                    "phase": phase_key.upper(),
                    "section": html_section,
                    "agent_responsible": agent_id,
                    "artifact_path": raw_path,
                    "finding_type": "missing_artifact",
                    "detail": (
                        f"{'Primary output' if is_primary else 'Output artifact'} "
                        f"'{raw_path}' declared for {agent_id} "
                        f"(phase {phase_key}) not found on disk."
                    ),
                    "root_cause": (
                        f"Agent {agent_id} did not produce the expected artifact, "
                        "or the path in artifact-map.yaml diverges from the actual "
                        "agent output location."
                    ),
                    "auto_correctable": True,  # F3 fix (2026-08-18): missing_artifact is auto-correctable per spec §4.5 Success Criteria
                    "suggested_fix": (
                        f"Re-run {agent_id} for project '{ctx.project}' and verify "
                        f"the output is written to '{raw_path}'. "
                        "If the path changed, update artifact-map.yaml accordingly."
                    ),
                })

    if findings:
        n_crit = sum(1 for f in findings if f["severity"] == "CRITICAL")
        return Result(
            False,
            f"{len(findings)} missing artifact(s) (CRITICAL={n_crit}, HIGH={len(findings)-n_crit})",
            extra=findings,
        )
    return Result(True, "all declared artifacts present for completed phases")


