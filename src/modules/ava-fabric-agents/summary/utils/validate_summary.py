def _extract_json_slice(html: str, key: str) -> Optional[str]:
    """Find `key: <value>,` inside the `const D = {` block and return the raw
    value up to the matching top-level separator. Handles strings, arrays,
    objects with nested braces."""
    m = re.search(r'[\s,\{]' + re.escape(key) + r'\s*:\s*', html)
    if not m:
        return None
    start = m.end()
    depth = 0
    in_str = False
    esc = False
    quote = ''
    i = start
    # Skip initial whitespace
    while i < len(html) and html[i] in ' \t':
        i += 1
    first = html[i] if i < len(html) else ''
    if first in ('"', "'"):
        # String literal
        quote = first
        i += 1
        while i < len(html):
            c = html[i]
            if esc:
                esc = False
            elif c == '\\':
                esc = True
            elif c == quote:
                return html[start:i + 1]
            i += 1
        return None
    if first in ('[', '{'):
        opener = first
        closer = ']' if opener == '[' else '}'
        while i < len(html):
            c = html[i]
            if esc:
                esc = False
            elif in_str:
                if c == '\\':
                    esc = True
                elif c == quote:
                    in_str = False
            elif c in ('"', "'"):
                in_str = True
                quote = c
            elif c == opener:
                depth += 1
            elif c == closer:
                depth -= 1
                if depth == 0:
                    return html[start:i + 1]
            i += 1
        return None
    # Primitive (number/bool/null)
    m2 = re.match(r'[^,\n}]+', html[start:])
    return m2.group(0) if m2 else None


def _extract_js_function(html: str, function_name: str) -> Optional[str]:
    """Extract a complete JavaScript function using balanced braces."""
    match = re.search(
        r"function\s+" + re.escape(function_name) + r"\s*\(\s*\)\s*\{",
        html,
    )
    if not match:
        return None
    start = match.start()
    opening = html.find("{", match.start(), match.end())
    depth = 0
    i = opening
    quote: Optional[str] = None
    escaped = False
    line_comment = False
    block_comment = False
    while i < len(html):
        char = html[i]
        next_char = html[i + 1] if i + 1 < len(html) else ""
        if line_comment:
            if char in "\r\n":
                line_comment = False
            i += 1
            continue
        if block_comment:
            if char == "*" and next_char == "/":
                block_comment = False
                i += 2
            else:
                i += 1
            continue
        if quote:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == quote:
                quote = None
            i += 1
            continue
        if char == "/" and next_char == "/":
            line_comment = True
            i += 2
            continue
        if char == "/" and next_char == "*":
            block_comment = True
            i += 2
            continue
        if char in ('"', "'", "`"):
            quote = char
            i += 1
            continue
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return html[start:i + 1]
        i += 1
    return None


def _try_json(raw: Optional[str]):
    if raw is None:
        return None
    try:
        return json.loads(raw)
    except Exception:
        return None


