def _c11_17(ctx: Ctx) -> Result:
    """Best-effort: no 'AG-NN' token may be displayed anywhere in the summary.
    Static HTML can't fully distinguish 'displayed' text from internal
    identifiers, so this targets two known display surfaces: (1) any AG-NN
    text in the static HTML body outside <script>…</script>, and (2) the
    AGENTS[] array's 'name:' field plus i18n dict *values* (not keys) inside
    the script block — both are rendered verbatim by the browser. Internal
    identifiers (i18n keys like 'card-arts-ag03', ids like 'chips-ag10', role
    keys like 'ag01-role') use lowercase 'ag' or are never rendered as text
    and are intentionally not flagged."""
    scripts = list(re.finditer(r'<script[^>]*>([\s\S]*?)</script>', ctx.html))
    offenders = []
    body = ctx.html
    for m in reversed(scripts):
        body = body[:m.start()] + body[m.end():]
    body_hits = _AG_NN_RE.findall(body)
    if body_hits:
        offenders.append(f"static body: {sorted(set(body_hits))[:5]}")
    for m in scripts:
        s = m.group(1)
        name_hits = re.findall(r'name\s*:\s*"[^"]*(AG-\d+)[^"]*"', s)
        i18n_hits = re.findall(r'"[a-z0-9-]+"\s*:\s*"[^"]*(AG-\d+)[^"]*"', s)
        if name_hits:
            offenders.append(f"AGENTS[].name: {sorted(set(name_hits))[:5]}")
        if i18n_hits:
            offenders.append(f"i18n value: {sorted(set(i18n_hits))[:5]}")
    return Result(not offenders, "no displayed 'AG-NN' token found (best-effort static scan)" if not offenders
                  else f"'AG-NN' still displayed: {offenders}")


