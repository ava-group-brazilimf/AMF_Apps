def _kpi_hidden_guard(ctx: Ctx) -> tuple[set, bool]:
    """Shared helper for C11.1/C11.2: KPI_HIDDEN_IF_EMPTY is a single array
    hiding a tile whenever its value is '0' OR 'N/D' (a tile can only ever be
    in one of those two states, so a per-key OR is equivalent to — and
    simpler than — separate zero/N-D lists)."""
    m = re.search(r"KPI_HIDDEN_IF_EMPTY\s*=\s*\[([^\]]*)\]", ctx.html)
    guard_keys = set(re.findall(r'[\'"]([^\'"]+)[\'"]', m.group(1))) if m else set()
    fn = re.search(r'function renderKPIs\(\)\{[\s\S]{0,900}?\n\s*\}', ctx.html)
    wired = bool(fn and re.search(
        r"KPI_HIDDEN_IF_EMPTY\.includes\(k\.k\)\s*&&\s*\(k\.v\s*===\s*'0'\s*\|\|\s*k\.v\s*===\s*'N/D'\)",
        fn.group(0)))
    return guard_keys, wired


