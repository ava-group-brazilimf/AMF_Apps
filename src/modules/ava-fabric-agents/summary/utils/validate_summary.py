def _fix_c3_10(ctx: Ctx) -> Optional[str]:
    """Fix literal \\n (backslash+n) in Mermaid quoted labels → <br/>.

    Two-phase repair:
    1. Rewrites source .mmd files under asis/diagrams/ and asis/db/ so the
       root cause is eliminated — subsequent builder runs will be clean.
    2. Patches the staticDiagrams JSON block embedded in the HTML so the
       current summary renders correctly without a full rebuild.

    Mirrors the rule added to sanitize_mmd() in the builder:
      \\n inside \"...\" node labels → <br/>  (Mermaid 11 htmlLabels syntax)."""

    def _fix_labels_in_mmd(text: str) -> str:
        """Replace \\n inside double-quoted Mermaid labels with <br/>.
        Actual newlines (line separators between statements) are untouched."""
        return re.sub(
            r'"([^"\n]*)"',
            lambda m: '"' + m.group(1).replace('\\n', '<br/>') + '"',
            text)

    # ── 1. Fix source .mmd files ──────────────────────────────────────────────
    for base in (ctx.outputs_dir / "asis" / "diagrams",
                 ctx.outputs_dir / "asis" / "db"):
        if not base.exists():
            continue
        for mmd in sorted(base.glob("*.mmd")):
            txt = mmd.read_text(encoding="utf-8", errors="replace")
            if not _MMD_LITERAL_NL_IN_LABEL_RE.search(txt):
                continue
            new_txt = _fix_labels_in_mmd(txt)
            if new_txt != txt:
                mmd.write_text(new_txt, encoding="utf-8")

    # ── 2. Patch staticDiagrams JSON block in the HTML ────────────────────────
    sd_raw = _extract_json_slice(ctx.html, 'staticDiagrams')
    if not sd_raw:
        return None
    sd = _try_json(sd_raw)
    if not isinstance(sd, dict):
        return None

    changed = False
    for key in list(sd.keys()):
        val = sd.get(key)
        if not isinstance(val, str):
            continue
        if not _MMD_LITERAL_NL_IN_LABEL_RE.search(val):
            continue
        sd[key] = _fix_labels_in_mmd(val)
        changed = True

    if not changed:
        return None

    new_json = json.dumps(sd)
    pos = ctx.html.find(sd_raw)
    if pos < 0:
        return None
    return ctx.html[:pos] + new_json + ctx.html[pos + len(sd_raw):]


def _c3_11(ctx: Ctx) -> Result:
    """The JS <script> data block must not contain a literal '</script>' string.

    The browser HTML parser (which has priority over the JS parser) treats the
    character sequence '</script>' as a closing tag even inside a <script>
    element.  When embedded HTML file content (e.g. prototype-asis/index.html)
    is serialised with plain json.dumps() into the D.fileTree JSON, any
    '</script>' in that content terminates the <script> block at that point.
    All JavaScript after that position (rendering functions, init(),
    DOMContentLoaded listener) is never parsed — the dashboard shows raw text.

    Fix: use safe_json() in the builder, which escapes '</' → '\\/' for all
    data injections.  '<\\/' is valid JSON per RFC 8259 §7 and produces the
    same runtime string value, but the HTML parser does not recognise it as
    a closing tag.
    """
    data_start = ctx.html.find('const D = {')
    script_end = ctx.html.rfind('</script>')
    if data_start < 0 or script_end < 0:
        return Result(False, "could not locate 'const D = {' or closing '</script>'")
    data_section = ctx.html[data_start:script_end]
    hits = [m.start() for m in re.finditer(r'</script>', data_section, re.IGNORECASE)]
    return Result(
        len(hits) == 0,
        "valid — no literal </script> inside data block" if not hits
        else f"CRITICAL: {len(hits)} literal </script> inside const D data block — "
             f"HTML parser terminates <script> prematurely. "
             f"Rebuild with safe_json() in build_summary_comprehensive.py.",
    )


def _fix_c3_11(ctx: Ctx) -> Optional[str]:
    """Patch the generated HTML in-place: escape '</' → '\\/' inside the data block.

    This is an emergency patch for already-generated files.  The correct
    long-term fix is rebuilding with safe_json() in the builder.
    """
    data_start = ctx.html.find('const D = {')
    script_end = ctx.html.rfind('</script>')
    if data_start < 0 or script_end < 0:
        return None
    before = ctx.html[:data_start]
    data = ctx.html[data_start:script_end]
    after = ctx.html[script_end:]
    if '</script>' not in data:
        return None
    fixed_data = data.replace('</', '<\\/')
    return before + fixed_data + after


def _c3_12(ctx: Ctx) -> Result:
    """No diagram value in D.staticDiagrams may start with a markdown fenced code block.

    Agents sometimes write .mmd files wrapped in markdown fences (```mermaid ... ```).
    When sanitize_mmd() fails to strip them, the content injected into D.staticDiagrams
    starts with '```mermaid\\n', which Mermaid.js cannot parse — it sees 'mermaid'
    as the diagram type keyword and throws:
      'No diagram type detected matching given configuration for text: ...'
      'Syntax error in text — mermaid version 11.x.x'
    Fix: sanitize_mmd() must strip the fence as the FIRST operation (before any
    other transforms). Also fix the source .mmd files.
    """
    sd = ctx.D_staticDiagrams or {}
    if not sd:
        return Result(True, "staticDiagrams absent or empty — skipped")
    fenced = [k for k, v in sd.items() if isinstance(v, str) and v.lstrip().startswith("```")]
    return Result(
        len(fenced) == 0,
        "all diagrams are fence-free" if not fenced
        else f"fenced diagrams found: {fenced} — Mermaid will throw 'Syntax error in text'",
    )


def _fix_c3_12(ctx: Ctx) -> Optional[str]:
    """Strip markdown fences from D.staticDiagrams values in the generated HTML.

    Locates fenced diagram strings inside the JS staticDiagrams block and
    removes the opening and closing ``` lines. Emergency in-place patch;
    the proper fix is rebuilding with the updated sanitize_mmd() in the builder.
    """
    def _strip_fence(s: str) -> str:
        s = s.strip()
        if not s.startswith("```"):
            return s
        lines = s.splitlines()
        lines = lines[1:]  # remove opening ```mermaid line
        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]
        return "\\n".join(lines).strip()

    sd = ctx.D_staticDiagrams or {}
    fenced = {k: v for k, v in sd.items() if isinstance(v, str) and v.lstrip().startswith("```")}
    if not fenced:
        return None

    html = ctx.html
    for key, val in fenced.items():
        fixed = _strip_fence(val)
        pattern = re.compile(
            r'("' + re.escape(key) + r'"\s*:\s*")' + re.escape(val[:60]),
            re.DOTALL)
        if pattern.search(html):
            html = pattern.sub(lambda m: m.group(1) + fixed, html, count=1)
    if html == ctx.html:
        return None
    ctx.html = html
    return html


def _strip_balanced_div_block(html: str, start_marker: str) -> Optional[str]:
    """Remove the first `<div …>…</div>` block whose opening tag starts at
    `start_marker`, tracking nesting depth so inner <div> children don't
    truncate the match early. Returns None if the marker isn't found."""
    start = html.find(start_marker)
    if start < 0:
        return None
    depth = 0
    end = None
    for m in re.finditer(r'<div\b|</div>', html[start:]):
        depth += 1 if m.group(0) == '<div' else -1
        if depth == 0:
            end = start + m.end()
            break
    if end is None:
        return None
    return html[:start] + html[end:]


