def _c3_2(ctx: Ctx) -> Result:
    diag_dir = ctx.outputs_dir / "asis" / "diagrams"
    db_dir = ctx.outputs_dir / "asis" / "db"
    if not diag_dir.exists():
        return Result(True, "no asis/diagrams; skipped")
    # Explicit stem → expected staticDiagrams key (matches collect_static_diagrams)
    STEM_TO_KEY = {
        "c4-context":            "c4ctx",
        "c4-container":          "c4cnt",
        "c4-component":          "c4comp",
        "component-diagram":     "comp",
        "seq-baixa-titulo-cp":   "seqBaixaCp",
        "seq-baixa-cp":          "seqBaixaCp",        # short alias
        "seq-cadastro-conta-pagar": "seqCadCp",
        "seq-cadastro-cp":       "seqCadCp",           # short alias
        "er-diagram":            "er",
        "c4-context-tobe":       "tobeC4",
        "migration-gantt":       "gantt",
    }
    sd = ctx.D_staticDiagrams or {}
    mmd_files = list(diag_dir.glob("*.mmd"))
    if db_dir.exists():
        mmd_files += list(db_dir.glob("*.mmd"))
    if not mmd_files:
        return Result(True, "no .mmd files; skipped")
    missing = []
    for m in mmd_files:
        expected_key = STEM_TO_KEY.get(m.stem)
        if expected_key is None:
            # Unknown diagram name — not in the contract; warn-level handled at catalog
            continue
        if not (isinstance(sd.get(expected_key), str) and sd[expected_key].strip()):
            missing.append(f"{m.name} → {expected_key}")
    ok = not missing
    return Result(ok, f"{len(mmd_files)} .mmd files, missing: {missing or 'none'}")

def _c3_3(ctx: Ctx) -> Result:
    sd = ctx.D_staticDiagrams or {}
    bad_chars = []
    for k, v in sd.items():
        if not isinstance(v, str):
            continue
        found = []
        if any(ord(c) > 0x1F300 and ord(c) < 0x1FAFF for c in v):
            found.append("emoji")
        if "→" in v:
            found.append("→")
        if "—" in v:
            found.append("—")
        if "`" in v:
            found.append("backtick")
        if found:
            bad_chars.append(f"{k}:{','.join(found)}")
    ok = not bad_chars
    return Result(ok, "sanitized" if ok else f"unsanitized: {bad_chars[:3]}")

