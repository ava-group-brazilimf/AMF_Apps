@dataclass
class Check:
    id: str
    category: str
    level: str            # "error" | "warn" | "info"
    description: str
    remediation: str
    check: Callable[["Ctx"], "Result"]
    # Optional auto-fix. Returns a new `html` string if the check can be
    # repaired in-place, or None if repair is not possible from the HTML alone
    # (e.g. missing data that must come from source files via the builder).
    # Fixes must be deterministic and idempotent.
    fix: Optional[Callable[["Ctx"], Optional[str]]] = None

    def __call__(self, ctx: "Ctx") -> "Result":
        try:
            return self.check(ctx)
        except Exception as e:
            return Result(ok=False, detail=f"validator crashed: {e!r}")

    def try_fix(self, ctx: "Ctx") -> Optional[str]:
        if self.fix is None:
            return None
        try:
            return self.fix(ctx)
        except Exception as e:
            print(f"   ⚠️ fix for {self.id} crashed: {e!r}")
            return None


@dataclass
class Result:
    ok: bool
    detail: str = ""
    extra: Optional[list] = None  # Rich finding dicts for deep-audit-report.json (DEEP_CHECKS only)


