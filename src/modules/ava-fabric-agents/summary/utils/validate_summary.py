def _write_deep_audit_json(ctx: Ctx, deep_results: list) -> None:
    """Write deep-audit-report.json (schema v1.1) from DEEP_CHECKS results.

    Flattens Result.extra finding dicts across all checks, assigns sequential
    DA-NNN IDs, runs a deduplication pass to suppress redundant missing_artifact
    findings from C12.6/C12.7 already covered by C12.3, computes severity
    counters, and writes to
    projects/{project}/outputs/summary/deep-audit-report.json.

    Valid finding_type values in schema v1.1:
        empty_by_failure | missing_artifact | divergent_config | mermaid_error |
        placeholder_unresolved | table_no_rows | list_no_items | parser_gap | render_gap

    Schema v1.1 adds three nullable fields to each finding emitted by C12.6/C12.7
    when the element is resolved via html_element_correlation:
        html_element_id  — value of the id= attribute (or null)
        d_field          — D.* field name (or null for uncorrelated elements)
        render_function  — JS render function name (or null for uncorrelated elements)
    """
    import json as _json
    import datetime as _datetime

    out_dir = ctx.outputs_dir / "summary"
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / "deep-audit-report.json"

    all_findings: list = []
    seq = 1
    for chk, res in deep_results:
        if not res.ok and res.extra:
            for finding in res.extra:
                enriched = dict(finding)
                enriched["id"] = f"DA-{seq:03d}"
                # Internal tag for deduplication pass — removed before serialisation.
                enriched["_src"] = chk.id
                all_findings.append(enriched)
                seq += 1

    # Deduplication pass (spec 042 §4.2 / AD-6):
    # If C12.3 already emitted a missing_artifact for a given artifact_path,
    # suppress any duplicate missing_artifact from C12.6/C12.7 for the same path.
    # C12.3 is at index 2 in DEEP_CHECKS, so its findings always precede C12.6/C12.7.
    c12_3_paths = {
        f["artifact_path"]
        for f in all_findings
        if (
            f.get("_src") == "C12.3"
            and f.get("finding_type") == "missing_artifact"
            and f.get("artifact_path") is not None
        )
    }
    if c12_3_paths:
        all_findings = [
            f for f in all_findings
            if not (
                f.get("_src") in ("C12.6", "C12.7")
                and f.get("finding_type") == "missing_artifact"
                and f.get("artifact_path") in c12_3_paths
            )
        ]

    # Remove internal tag — must never appear in the serialised JSON.
    for f in all_findings:
        f.pop("_src", None)

    sev_counts: dict = {"CRITICAL": 0, "HIGH": 0, "MEDIUM": 0, "LOW": 0}
    for f in all_findings:
        sev = f.get("severity", "LOW")
        if sev in sev_counts:
            sev_counts[sev] += 1

    promotable = sev_counts["CRITICAL"] == 0 and sev_counts["HIGH"] == 0

    report = {
        "schema_version": "1.1",
        "generated_at": _datetime.datetime.utcnow().isoformat(timespec="seconds") + "Z",
        "project": ctx.project,
        "html_path": str(ctx.html_path),
        "summary": {
            "critical":   sev_counts["CRITICAL"],
            "high":       sev_counts["HIGH"],
            "medium":     sev_counts["MEDIUM"],
            "low":        sev_counts["LOW"],
            "promotable": promotable,
        },
        "findings": all_findings,
    }

    with out_path.open("w", encoding="utf-8") as fh:
        _json.dump(report, fh, indent=2, ensure_ascii=False)

    print(
        f"[deep-audit] {out_path} written "
        f"({len(all_findings)} finding(s), promotable={promotable})"
    )


