# ─────────────────────────────────────────────────────────────────
#  _auto_detect_d_field — JS-based D-field discovery for unmapped ids
# ─────────────────────────────────────────────────────────────────

def _auto_detect_d_field(html: str, element_id: str) -> Optional[str]:
    """Try to infer the D.* field that populates a given element id by scanning
    all <script> blocks in the HTML for the element_id string and extracting
    the first nearby ``D.<field>`` reference.

    Returns the field name (e.g. ``"coverageGapStrategy"``) or ``None`` if the
    element id is not found in any script block or has no D.* references nearby.

    This is used as a STEP 2b fallback in ``_classify_empty_element`` when an
    element id is not present in the ``html_element_correlation`` map, so that
    C12.6/C12.7 can still classify the empty element as ``parser_gap`` (HIGH) or
    ``render_gap`` (MEDIUM) rather than the generic ``table_no_rows`` (HIGH) with
    no root-cause information.
    """
    scripts = re.findall(r"<script[^>]*>(.*?)</script>", html, re.DOTALL | re.IGNORECASE)
    js_all = "\n".join(scripts)

    m = re.search(re.escape(element_id), js_all)
    if not m:
        return None

    # 300-char window around the reference
    snippet = js_all[max(0, m.start() - 300): m.end() + 300]
    d_fields = re.findall(r"D\.([a-zA-Z][a-zA-Z0-9_]+)", snippet)
    if not d_fields:
        return None

    # Remove common noise tokens that are object accessors, not data fields
    _NOISE = {"length", "push", "filter", "map", "forEach", "indexOf", "find",
              "slice", "join", "some", "every", "reduce", "includes", "sort"}
    for f in d_fields:
        if f not in _NOISE:
            return f
    return None


# ─────────────────────────────────────────────────────────────────
#  _classify_empty_element — shared helper for C12.6 / C12.7
# ─────────────────────────────────────────────────────────────────

def _classify_empty_element(
    ctx: Ctx,
    element_html: str,
    corr_map: dict,
    *,
    native_finding_type: str,
    native_severity: str,
) -> Optional[dict]:
    """Classify an empty HTML table/list element using the html_element_correlation map.

    Applies a 6-step decision tree to identify the root cause of an empty table or
    list element detected by C12.6 / C12.7.

    Args:
        ctx: Validation context containing HTML, project_dir, and D.* data.
        element_html: Raw HTML of the empty element (table or ul/ol).
        corr_map: The html_element_correlation dict loaded from artifact-map.yaml.
        native_finding_type: Finding type to emit for fallback / uncorrelated elements
            (e.g. ``"table_no_rows"`` or ``"list_no_items"``).
        native_severity: Severity to use for fallback findings (e.g. ``"HIGH"`` or
            ``"MEDIUM"``).

    Returns one of four possible outcomes:

        - ``dict`` with ``finding_type == native_finding_type``: element has no ``id=``
          attribute, or its id is not in the correlation map — fallback heuristic applied.
        - ``dict`` with ``finding_type == "missing_artifact"``: correlated artifact does
          not exist on disk or is empty (``auto_correctable=True``).
        - ``dict`` with ``finding_type == "parser_gap"``: artifact exists but the
          corresponding ``D.*`` field in the HTML is empty or null (severity HIGH,
          ``auto_correctable=False``).
        - ``dict`` with ``finding_type == "render_gap"``: ``D.*`` field has data but the
          DOM element still renders empty (severity MEDIUM, ``auto_correctable=False``).
        - ``None``: the element's phase has not been executed yet — this is a legitimate
          empty state, not a finding. No entry is added to ``findings[]``.
    """
    # STEP 1 — Resolve element id
    id_match = re.search(r'id="([^"]+)"', element_html)
    if id_match is None:
        # No id attribute — fall back to heading heuristic.
        # Severity capped at LOW: without an id we cannot phase-gate this element,
        # so emitting HIGH/MEDIUM would create false positives for legitimately
        # empty sections whose phase hasn't run yet.
        heading = re.search(
            r'<(?:h[1-6]|caption)[^>]*>(.*?)</(?:h[1-6]|caption)>',
            element_html, re.IGNORECASE,
        )
        if heading is None:
            # Completely unidentifiable element — no id= and no heading.
            # Most likely a structural/layout element (nav, sidebar, template
            # scaffold). Cannot phase-gate it, cannot identify its D.* field.
            # Suppress to avoid systematic false-positives for layout tables/lists.
            return None
        hint = re.sub(r'<[^>]+>', '', heading.group(1)).strip() or "unidentified section"
        return {
            "severity": "LOW",
            "phase": "MULTIPLE",
            "section": hint,
            "agent_responsible": "ava-summary",
            "artifact_path": None,
            "html_element_id": None,
            "d_field": None,
            "render_function": None,
            "finding_type": native_finding_type,
            "detail": f"Element has no id= attribute; heading '{hint}' used as hint.",
            "root_cause": "Element id absent — update correlation map or assign a fixed id.",
            "auto_correctable": False,
            "suggested_fix": (
                "Assign a fixed id= to this element in the Summary template "
                "and add a corresponding entry to artifact-map.yaml html_element_correlation."
            ),
        }

    id_value = id_match.group(1)

    # STEP 2 — Look up id in html_element_correlation map
    corr = corr_map.get(id_value)
    if corr is None:
        # STEP 2b — id not in map: try to auto-detect the D.* field from JS context
        # so we can still classify as parser_gap / render_gap rather than emit a
        # generic HIGH finding that drowns out real issues.
        auto_d = _auto_detect_d_field(ctx.html, id_value)
        if auto_d is not None:
            raw_slice = _extract_json_slice(ctx.html, auto_d)
            d_has_data = raw_slice is not None and len(raw_slice.strip()) > 4
            if not d_has_data:
                # Severity is MEDIUM (not HIGH) because phase status is UNKNOWN —
                # the element may legitimately be empty if its phase hasn't run yet.
                # Add it to the correlation map to get accurate phase-gated classification.
                return {
                    "severity": "MEDIUM",
                    "phase": "UNKNOWN",
                    "section": f"auto-detected D.{auto_d}",
                    "agent_responsible": "ava-summary",
                    "artifact_path": None,
                    "html_element_id": id_value,
                    "d_field": auto_d,
                    "render_function": None,
                    "finding_type": "parser_gap",
                    "detail": (
                        f"D.{auto_d} is empty in the HTML data block even though "
                        f"element #{id_value} exists (auto-detected D-field; phase "
                        f"status unknown — add '{id_value}' to artifact-map.yaml for "
                        f"accurate phase-gated classification)."
                    ),
                    "root_cause": (
                        f"Parser for D.{auto_d} in build_summary_comprehensive.py "
                        f"returned no data, OR the phase that produces D.{auto_d} "
                        f"has not yet been executed. Phase unknown — add element to "
                        f"html_element_correlation map for confirmation."
                    ),
                    "auto_correctable": False,
                    "suggested_fix": (
                        f"1) Add '{id_value}' to artifact-map.yaml html_element_correlation "
                        f"with artifact_path, phase, section, and agent_responsible. "
                        f"2) If phase IS executed and D.{auto_d} is still empty, fix the "
                        f"parser for D.{auto_d} in build_summary_comprehensive.py."
                    ),
                }
            # D.* has data → JS will render the table at browser runtime.
            # See STEP 6 comment in the correlated-element branch for the rationale:
            # all Summary tables are JS-rendered; static-HTML tbody is always empty.
            # Do NOT emit render_gap — it would be a systematic false positive.
            return None  # empty_legitimate (JS renders at runtime from D.* data)

        # No D-field detected — element may be static / server-rendered / truly unknown.
        # Emit LOW (not HIGH) to avoid drowning out real parser_gap/missing_artifact findings.
        return {
            "severity": "LOW",
            "phase": "MULTIPLE",
            "section": "unidentified section",
            "agent_responsible": "ava-summary",
            "artifact_path": None,
            "html_element_id": id_value,
            "d_field": None,
            "render_function": None,
            "finding_type": native_finding_type,
            "detail": (
                f"Element id='{id_value}' is not in the html_element_correlation map "
                f"and its D.* field could not be auto-detected from JS context."
            ),
            "root_cause": (
                "element id not in correlation map — update artifact-map.yaml "
                "html_element_correlation"
            ),
            "auto_correctable": False,
            "suggested_fix": (
                f"Add an entry for '{id_value}' to artifact-map.yaml "
                "html_element_correlation with the correct d_field, artifact_path, "
                "render_function, phase, section, and agent_responsible."
            ),
        }

    # STEP 3 — Gate A: phase not yet executed (coarse check)
    # .lower() is MANDATORY: phase keys in YAML are uppercase (e.g. "F5"),
    # but _is_phase_done() expects lowercase ("f5").
    if not _is_phase_done(ctx, corr["phase"].lower()):
        print(
            f"[C12.6/DEBUG] Skipping element id='{id_value}' — phase '{corr['phase']}' not yet executed.",
            file=sys.stderr,
        )
        return None  # Legitimate empty state — NO finding emitted

    # STEP 3.5 — Gate B: specific agent responsible for this artifact is pending.
    # PHASE_KEY_MAP is coarse: _is_phase_done("f5") returns True if ANY ava-qa-*
    # agent ran, even when the specific agent that produces this artifact is "pending".
    # This gate catches that case to suppress false-positive missing_artifact findings
    # for optional pipeline agents that simply have not been invoked yet.
    # If the agent is absent from D.agentStatus entirely (None) it was never tracked/run →
    # treat as "pending" and suppress (same semantics: don't penalise un-run agents).
    responsible_agent = corr.get("agent_responsible", "")
    if responsible_agent:
        agent_status = (ctx.D_agentStatus or {}).get(responsible_agent)
        if agent_status != "done":  # catches: None (not tracked), "pending", "running", etc.
            print(
                f"[C12.6/DEBUG] Skipping element id='{id_value}' — "
                f"agent '{responsible_agent}' status='{agent_status}' (not done).",
                file=sys.stderr,
            )
            return None  # Agent never ran → legitimate empty, suppress finding

    # STEP 4 — Resolve origin artifact on disk
    artifact_full_path = ctx.project_dir / corr["artifact_path"]
    if not artifact_full_path.exists() or artifact_full_path.stat().st_size == 0:
        # Check alternatives before emitting missing_artifact.
        # When an alternative exists the agent ran (just for a different stack) —
        # suppress the finding entirely so non-.NET sections don't block promotable.
        for _alt_raw in (corr.get("alternatives") or []):
            _alt_path = (
                ctx.project_dir / _alt_raw
                if not Path(_alt_raw).is_absolute()
                else Path(_alt_raw)
            )
            if _alt_path.exists() and _alt_path.stat().st_size > 0:
                return None  # Alternative artifact found — suppress finding
        return {
            "severity": native_severity,
            "phase": corr["phase"],
            "section": corr["section"],
            "agent_responsible": corr["agent_responsible"],
            "artifact_path": corr["artifact_path"],
            "html_element_id": id_value,
            "d_field": corr["d_field"],
            "render_function": corr["render_function"],
            "finding_type": "missing_artifact",
            "detail": (
                f"Artifact '{corr['artifact_path']}' does not exist or is empty on disk."
            ),
            "root_cause": (
                f"Agent {corr['agent_responsible']} did not produce the expected output "
                f"for phase {corr['phase']}."
            ),
            "auto_correctable": True,
            "suggested_fix": (
                f"Re-run {corr['agent_responsible']} to regenerate "
                f"'{corr['artifact_path']}'."
            ),
        }

    # STEP 5 — Check D.* field in the HTML data block
    raw_slice = _extract_json_slice(ctx.html, corr["d_field"])
    d_field_has_data = raw_slice is not None and len(raw_slice.strip()) > 4
    # len > 4 excludes: '[]', '{}', '""''null'

    if not d_field_has_data:
        # STEP 5a — Before emitting parser_gap HIGH, verify the artifact does not
        # explicitly declare "0 items". When a parser intentionally returns [] because
        # the source data has zero entries (e.g. "Stored Procedures: 0"), D.* empty is
        # correct, NOT a parser failure. Reading the first 2 KB of the artifact is cheap
        # and avoids false-positive HIGH findings that block promotable.
        artifact_full_path2 = ctx.project_dir / corr["artifact_path"]
        try:
            artifact_head = artifact_full_path2.read_text("utf-8", errors="replace")[:2048]
            _EXPLICIT_ZERO_RE = re.compile(
                r"(\|\s*[^|]+\|\s*0\s*\|"        # markdown table: | Category | 0 |
                r"|no\s+\w+\s+found"              # "No stored procedures found"
                r"|0\s+(?:stored\s+procedures?|functions?|triggers?|events?|items?)"
                r"|count[:\s]+0"                  # "count: 0"
                r"|\*\*\s*0\s+\w)",               # "**0 items"
                re.IGNORECASE,
            )
            if _EXPLICIT_ZERO_RE.search(artifact_head):
                print(
                    f"[C12.6/DEBUG] Suppressing parser_gap for id='{id_value}' — "
                    f"artifact '{corr['artifact_path']}' explicitly documents 0 items.",
                    file=sys.stderr,
                )
                return None  # Legitimately zero — D.* empty is correct, not a parser bug
        except Exception:
            pass  # If we can't read the artifact, proceed with normal parser_gap emission

        return {
            "severity": "HIGH",
            "phase": corr["phase"],
            "section": corr["section"],
            "agent_responsible": corr["agent_responsible"],
            "artifact_path": corr["artifact_path"],
            "html_element_id": id_value,
            "d_field": corr["d_field"],
            "render_function": corr["render_function"],
            "finding_type": "parser_gap",
            "detail": (
                f"D.{corr['d_field']} is empty/null in the HTML even though "
                f"'{corr['artifact_path']}' exists on disk."
            ),
            "root_cause": (
                f"Parser responsible for D.{corr['d_field']} in "
                "build_summary_comprehensive.py either did not run, failed silently, "
                "matched zero patterns, or was not invoked in the data-injection function."
            ),
            "auto_correctable": False,
            "suggested_fix": (
                f"Artifact '{corr['artifact_path']}' exists but D.{corr['d_field']} "
                f"is empty/null in the HTML. "
                f"Re-run build_summary_comprehensive.py and inspect its captured "
                f"output to find the parser responsible for D.{corr['d_field']} — it "
                f"either did not run, did not find the expected pattern, or was not "
                f"called in the data-injection function."
            ),
        }

    # STEP 6 — D.* field has data and element is empty in static HTML.
    # The Summary HTML uses JavaScript rendering for ALL tables: <tbody id="tb-*"> are
    # empty in the static source and populated by renderXxx() functions at browser runtime.
    # When D.* is populated, the JS function WILL render the table — the static-HTML check
    # therefore always sees an empty tbody even when the page works correctly in a browser.
    # Emitting render_gap here would be a systematic false positive (N=18+ per run).
    #
    # A genuine JS-side render bug (TypeError, wrong key) would require Playwright to
    # detect; that falls under the Playwright Mermaid Gate / Phase 3.5, not this check.
    # Returning None is the correct action: D.* populated → JS renders → not a bug.
    return None  # empty_legitimate (JS renders at runtime from D.* data)

# ─────────────────────────────────────────────────────────────────
#  C12.6 — table_no_rows
# ─────────────────────────────────────────────────────────────────

def _c12da_6(ctx: Ctx) -> Result:
    """C12.6 — No <table> has a <tbody> that exists but contains zero <tr>.

    Structural distinction from C11.41 / _c12_3 (Op\u00e7\u00e3o C, 2026-08-18):
      \u2022 C11.41 (_c12_3): targets tables where <tbody> is ENTIRELY ABSENT while
        <thead> is present (missing body element).
      \u2022 C12.6: targets tables where <tbody> EXISTS but has ZERO <tr> elements
        (body rendered empty).
    These two patterns are MUTUALLY EXCLUSIVE. Do NOT expand C12.6 to include
    tbody-absent tables \u2014 that would cause double-reporting with C11.41.
    (Op\u00e7\u00e3o C, 2026-08-18)
    """
    corr_map = _load_artifact_map().get("html_element_correlation", {})
    tables = re.findall(
        r'<table[^>]*>.*?</table>', ctx.html, re.DOTALL | re.IGNORECASE
    )
    findings: list = []

    for table_html in tables:
        tbody_match = re.search(
            r'<tbody[^>]*>(.*?)</tbody>', table_html, re.DOTALL | re.IGNORECASE
        )
        if tbody_match is None:
            # tbody ABSENT entirely \u2014 this is C11.41\u2019s domain, NOT C12.6.
            continue

        tbody_content = tbody_match.group(1)
        if re.search(r'<tr[\s>]', tbody_content, re.IGNORECASE):
            continue  # Has rows \u2014 fine

        # <tbody> EXISTS but has zero <tr> \u2014 C12.6\u2019s domain.
        # Delegate to helper for per-element classification (spec 042 §4.1).
        result = _classify_empty_element(
            ctx, table_html, corr_map,
            native_finding_type="table_no_rows",
            native_severity="HIGH",
        )
        if result is not None:
            findings.append(result)

    if not findings:
        return Result(True, "no tables with present-but-empty <tbody> found")

    return Result(
        False,
        f"HIGH: {len(findings)} table(s) with <tbody> present but empty",
        extra=findings,
    )


