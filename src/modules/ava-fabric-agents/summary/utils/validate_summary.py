#  C12.7 — list_no_items
# ─────────────────────────────────────────────────────────────────

def _c12da_7(ctx: Ctx) -> Result:
    """C12.7 — No <ul> or <ol> contains zero <li> elements. Severity: MEDIUM."""
    corr_map = _load_artifact_map().get("html_element_correlation", {})
    lists = re.findall(
        r'<(?:ul|ol)[^>]*>.*?</(?:ul|ol)>', ctx.html, re.DOTALL | re.IGNORECASE
    )
    findings: list = []

    for lst_html in lists:
        if re.search(r'<li[\s>]', lst_html, re.IGNORECASE):
            continue  # Has items \u2014 fine

        # Empty list \u2014 delegate to helper for per-element classification (spec 042 §4.1).
        result = _classify_empty_element(
            ctx, lst_html, corr_map,
            native_finding_type="list_no_items",
            native_severity="MEDIUM",
        )
        if result is not None:
            findings.append(result)

    if not findings:
        return Result(True, "no empty <ul>/<ol> elements found")

    return Result(
        False,
        f"MEDIUM: {len(findings)} empty list element(s) (<ul>/<ol> with zero <li>)",
        extra=findings,
    )


