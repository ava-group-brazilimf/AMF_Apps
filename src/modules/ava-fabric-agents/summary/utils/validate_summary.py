def _c11_20(ctx: Ctx) -> Result:
    """D.risks must reflect the ACTUAL item count in the risk source, not
    just be non-empty — guards against the Risk Register silently rendering
    '0 riscos' (or an undercount) when only risk-register.md exists (some
    pipeline variants, e.g. AST extraction, emit the markdown register
    instead of risk-register.json). The displayed count must always equal
    the number of items found in the source file (explicit heuristic)."""
    asis_dir = ctx.outputs_dir / "asis"
    json_path = asis_dir / "risk-register.json"
    md_path = asis_dir / "risk-register.md"
    source_count = None
    if json_path.exists():
        try:
            data = json.loads(json_path.read_text(encoding="utf-8", errors="replace"))
            risks = data.get("risks", data) if isinstance(data, dict) else data
            if isinstance(risks, list) and risks:
                source_count = len(risks)
        except (json.JSONDecodeError, OSError):
            pass
    if source_count is None and md_path.exists():
        text = md_path.read_text(encoding="utf-8", errors="replace")
        m = re.search(r'##\s*Risk Register\s*\n(.*?)(?=\n##\s|\Z)', text, re.DOTALL)
        if m:
            row_ids = re.findall(r'^\|\s*([A-Za-z]+-\d+)\s*\|', m.group(1), re.MULTILINE)
            if row_ids:
                source_count = len(set(row_ids))
    if source_count is None:
        return Result(True, "no risk source with data found; D.risks empty is correct")
    m = re.search(r'\brisks\s*:\s*(\[[\s\S]*?\])\s*,\s*\n', ctx.html)
    html_ids = re.findall(r'"id"\s*:\s*"([^"]+)"', m.group(1)) if m else []
    html_count = len(set(html_ids))
    ok = html_count == source_count
    return Result(ok, f"D.risks count matches source ({html_count})" if ok
                  else f"D.risks has {html_count} unique risk(s) but the source has {source_count} — "
                       "displayed count must equal the actual item count in risk-register.json/.md")


