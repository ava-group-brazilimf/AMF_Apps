def _load_ctx(project_name: str) -> Ctx:
    project_dir = Path(f"projects/{project_name}")
    outputs_dir = project_dir / "outputs"
    summary_dir = outputs_dir / "summary"
    # Pick the most recent AVA-FABRIC-SUMMARY-*.html
    candidates = sorted(summary_dir.glob("AVA-FABRIC-SUMMARY-*.html"), key=lambda p: p.stat().st_mtime, reverse=True)
    if not candidates:
        raise FileNotFoundError(f"No AVA-FABRIC-SUMMARY-*.html in {summary_dir}")
    html_path = candidates[0]
    html = html_path.read_text(encoding="utf-8", errors="replace")

    shared_ctx_path = project_dir / "context" / "shared-context.md"
    shared_context = shared_ctx_path.read_text(encoding="utf-8", errors="replace") if shared_ctx_path.exists() else ""

    config = {}
    cfg_path = project_dir / "context" / "project-config.yaml"
    if cfg_path.exists() and yaml is not None:
        try:
            config = yaml.safe_load(cfg_path.read_text(encoding="utf-8")) or {}
        except Exception:
            config = {}

    ctx = Ctx(project=project_name, project_dir=project_dir, outputs_dir=outputs_dir,
              html_path=html_path, html=html, shared_context=shared_context, config=config)
    _load_js_data(ctx)
    return ctx


def _format_md(results: list[tuple[Check, Result]], ctx: Ctx, applied_fixes: Optional[list[str]] = None) -> str:
    passed = [c for c, r in results if r.ok]
    errors = [(c, r) for c, r in results if not r.ok and c.level == "error"]
    warns = [(c, r) for c, r in results if not r.ok and c.level == "warn"]
    infos = [(c, r) for c, r in results if not r.ok and c.level == "info"]
    lines = []
    ts = datetime.now(timezone.utc).astimezone().strftime("%Y-%m-%d %H:%M %Z")
    lines.append(f"# Summary Validation Report — {ctx.project} · {ts}\n")
    lines.append(f"- **HTML**: `{ctx.html_path.relative_to(ctx.project_dir.parent.parent) if ctx.project_dir.is_relative_to(Path.cwd()) else ctx.html_path.name}`  ")
    lines.append(f"- **Size**: {len(ctx.html):,} bytes\n")
    lines.append("| Level | Count |")
    lines.append("|---|---|")
    lines.append(f"| ✅ Passed | {len(passed)} |")
    lines.append(f"| ⚠️ Warnings | {len(warns)} |")
    lines.append(f"| ❌ Errors | {len(errors)} |")
    if infos:
        lines.append(f"| ℹ️ Info | {len(infos)} |")
    lines.append("")
    if applied_fixes:
        lines.append(f"## 🔧 Auto-fixes applied ({len(applied_fixes)})")
        lines.append("")
        for fid in applied_fixes:
            lines.append(f"- **{fid}** auto-repaired in-place. Also update the builder so this doesn't regress again next run.")
        lines.append("")

    if errors:
        lines.append("## ❌ Errors (must fix before promoting)\n")
        for c, r in errors:
            lines.append(f"### {c.id} — {c.description}")
            lines.append(f"- **Category**: {c.category}")
            lines.append(f"- **Detail**: {r.detail}")
            lines.append(f"- **Remediation**: {c.remediation}\n")

    if warns:
        lines.append("## ⚠️ Warnings (drift — investigate if unexpected)\n")
        for c, r in warns:
            lines.append(f"- **{c.id}** [{c.category}] — {c.description}: {r.detail}")
            lines.append(f"  - *Remediation*: {c.remediation}")
        lines.append("")

    # Grouped full list
    by_cat: dict[str, list] = {}
    for c, r in results:
        by_cat.setdefault(c.category, []).append((c, r))
    lines.append("## Full check list\n")
    for cat, items in by_cat.items():
        ok_n = sum(1 for _, rr in items if rr.ok)
        lines.append(f"### {cat} ({ok_n}/{len(items)})")
        for c, r in items:
            icon = "✅" if r.ok else ("⚠️" if c.level == "warn" else ("ℹ️" if c.level == "info" else "❌"))
            lines.append(f"- {icon} **{c.id}** — {c.description} — `{r.detail}`")
        lines.append("")
    return "\n".join(lines)


def _format_json(results: list[tuple[Check, Result]], ctx: Ctx, applied_fixes: Optional[list[str]] = None) -> dict:
    return {
        "project": ctx.project,
        "html": str(ctx.html_path),
        "html_size": len(ctx.html),
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "applied_fixes": applied_fixes or [],
        "summary": {
            "passed": sum(1 for _, r in results if r.ok),
            "warn": sum(1 for c, r in results if not r.ok and c.level == "warn"),
            "error": sum(1 for c, r in results if not r.ok and c.level == "error"),
            "info": sum(1 for c, r in results if not r.ok and c.level == "info"),
        },
        "checks": [
            {
                "id": c.id, "category": c.category, "level": c.level,
                "description": c.description, "status": "pass" if r.ok else "fail",
                "detail": r.detail, "remediation": c.remediation,
            }
            for c, r in results
        ],
    }


def _run_checks(ctx: Ctx):
    # Re-load extracted data (since ctx.html may have been patched)
    _load_js_data(ctx)
    results = [(c, c(ctx)) for c in CHECKS]
    # Compatibility is a fail-closed pre-publication concern. The generated
    # report is read-only here; this validator never repairs or discovers .mmd.
    compat_path = ctx.outputs_dir / "summary" / "compatibility" / "blueprint-compatibility-report.json"
    if compat_path.is_file():
        try:
            payload = json.loads(compat_path.read_text(encoding="utf-8"))
            allowed = payload.get("publicationAllowed") is True
            results.append((Check("C13.1", "Blueprint Compatibility", "error", "Required Blueprints render with the Summary Mermaid runtime", "Resolve blueprint-compatibility-report.json before publication.", lambda _ctx, ok=allowed: Result(ok, "publicationAllowed=true" if ok else "publicationAllowed=false")), Result(allowed, "publicationAllowed=true" if allowed else "publicationAllowed=false")))
        except (OSError, json.JSONDecodeError):
            results.append((Check("C13.1", "Blueprint Compatibility", "error", "Compatibility report is readable", "Regenerate the compatibility report before publication.", lambda _ctx: Result(False, "Compatibility report unreadable")), Result(False, "Compatibility report unreadable")))
    else:
        results.append((Check("C13.1", "Blueprint Compatibility", "error", "Compatibility report exists before publication", "Run the Summary compatibility gate before publishing HTML.", lambda _ctx: Result(False, "Compatibility report missing")), Result(False, "Compatibility report missing")))

    # C13.2 — Mermaid Gate: reads mermaid-validation-report.json produced by Phase G
    # in build_summary_comprehensive or Phase 3.5 in remediate_summary.
    # This validator NEVER invokes Playwright directly — only consumes the pre-built report.
    mermaid_report_path = ctx.outputs_dir / "summary" / "mermaid-validation-report.json"
    if mermaid_report_path.is_file():
        try:
            _mermaid_payload = json.loads(mermaid_report_path.read_text(encoding="utf-8"))
            _mermaid_status  = _mermaid_payload.get("overall_status", "")
            # PASS, PASS_WITH_FIXES, DISABLED, SKIPPED are all acceptable —
            # only FAIL indicates unresolved diagrams that block publication.
            _mermaid_ok = _mermaid_status in ("PASS", "PASS_WITH_FIXES", "DISABLED", "SKIPPED")
            _mermaid_msg = f"overall_status={_mermaid_status}"
            results.append((
                Check(
                    "C13.2",
                    "Mermaid Gate",
                    "error",
                    "All Mermaid diagrams pass the Playwright rendering gate",
                    "Resolve failing diagrams or run with --skip-mermaid-gate if intentionally disabled.",
                    lambda _ctx, ok=_mermaid_ok: Result(ok, _mermaid_msg),
                ),
                Result(_mermaid_ok, _mermaid_msg),
            ))
        except (OSError, json.JSONDecodeError):
            results.append((
                Check(
                    "C13.2",
                    "Mermaid Gate",
                    "error",
                    "Mermaid gate report is readable",
                    "Re-run the build with the Mermaid gate enabled to regenerate the report.",
                    lambda _ctx: Result(False, "mermaid-validation-report.json unreadable"),
                ),
                Result(False, "mermaid-validation-report.json unreadable"),
            ))
    # If the report file does not exist (gate never ran), C13.2 is silently omitted
    # to preserve backwards-compatibility with pre-feature builds.

    return results


def _try_auto_fix(ctx: Ctx, results) -> tuple[list[str], bool]:
    """Apply all available `fix` functions for currently failing checks.

    Returns (fixed_ids, html_changed). Fixes are applied sequentially; ctx.html
    is mutated in place. Non-fixable failures are left for the next validation
    pass (the builder may need to re-run for data-level regressions)."""
    fixed: list[str] = []
    changed = False
    for chk, res in results:
        if res.ok or chk.fix is None:
            continue
        new_html = chk.try_fix(ctx)
        if new_html is None or new_html == ctx.html:
            continue
        ctx.html = new_html
        fixed.append(chk.id)
        changed = True
    return fixed, changed


def run_all(project_name: str, strict: bool = True, auto_fix: bool = False, max_fix_passes: int = 2, deep: bool = False) -> int:
    ctx = _load_ctx(project_name)
    results = _run_checks(ctx)
    applied_fixes: list[str] = []
    # Auto-fix loop (idempotent fixes; re-validate after each pass).
    if auto_fix:
        for _pass in range(max_fix_passes):
            err_before = sum(1 for c, r in results if not r.ok and c.level == "error")
            if err_before == 0:
                break
            fixed, changed = _try_auto_fix(ctx, results)
            if not changed:
                break
            applied_fixes.extend(fixed)
            # Persist patched HTML back to disk
            ctx.html_path.write_text(ctx.html, encoding="utf-8")
            print(f"   🔧 Auto-fix pass — applied: {', '.join(fixed)}")
            results = _run_checks(ctx)
    # — Deep Item Audit (C12.x) — activated only with --deep (spec 041, task 2.5).
    # When deep=False: this block is fully skipped; C1–C11+C13.x are the only rules;
    # exit code semantics are IDENTICAL to pre-041 behaviour (100% retrocompatible).
    if deep:
        print("   🔍 Running Deep Item Audit (C12.1–C12.7) …")
        deep_results = _run_deep_checks(ctx)
        _write_deep_audit_json(ctx, deep_results)
        results = results + deep_results  # Merge for unified summary table
    # Build result summary (no report files written to summary dir)
    jb = _format_json(results, ctx, applied_fixes=applied_fixes)
    # Exit code
    err = jb["summary"]["error"]
    warn = jb["summary"]["warn"]
    passed = jb["summary"]["passed"]
    suffix = f" (auto-fixed: {len(applied_fixes)})" if applied_fixes else ""
    deep_tag = " [+DEEP C12.x]" if deep else ""
    print(f"   📋 Validation{deep_tag}: {passed} passed · {warn} warnings · {err} errors{suffix}")
    if err > 0:
        print(f"   ❌ {err} error(s) remain after auto-fix")
        return 1
    print(f"   ✅ All error-level checks passed")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="Validate a generated Summary HTML against the non-regression rule catalog.")
    ap.add_argument("--project", required=True)
    ap.add_argument("--strict", action="store_true", default=True,
                    help="Exit with 1 if any error check fails after fixes (default).")
    ap.add_argument("--fix", action="store_true", default=False,
                    help="Attempt safe auto-repair of fixable regressions (placeholder leftovers, duplicate Mermaid, diagram sanitization, dead code).")
    ap.add_argument("--no-fix", dest="fix", action="store_false",
                    help="Disable auto-fix (report only).")
    ap.add_argument("--deep", action="store_true", default=False,
                    help="Activate C12 Deep Item Audit rules (C12.1–C12.7). "
                         "Without this flag, only C1–C11 rules run (backward-compatible). "
                         "Emits deep-audit-report.json alongside the standard validation-report.json.")
    args = ap.parse_args()
    return run_all(args.project, strict=args.strict, auto_fix=args.fix, deep=args.deep)


if __name__ == "__main__":
    sys.exit(main())
