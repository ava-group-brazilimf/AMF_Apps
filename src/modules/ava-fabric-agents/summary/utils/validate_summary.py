def _c1_2(ctx: Ctx) -> Result:
    # Mermaid inlined when the generated HTML is > 1 MB and contains typical
    # mermaid internals. We sanity-check via a substring search.
    has_marker = "mermaid-version" in ctx.html or "MermaidError" in ctx.html or "mermaid.init" in ctx.html
    size_ok = len(ctx.html) > 1_000_000
    if size_ok and has_marker:
        return Result(True, f"html={len(ctx.html):,} bytes, mermaid markers present")
    return Result(False, f"html={len(ctx.html):,} bytes; markers={has_marker}")

def _c1_3(ctx: Ctx) -> Result:
    # Unresolved {{X}} anywhere (skip {{X}} inside embedded JS-string
    # examples or regex literals is hard — we accept 0 tolerance in the
    # generated HTML because the builder's final sweep should remove them).
    leftovers = sorted(set(re.findall(r'\{\{[A-Z0-9_]+\}\}', ctx.html)))
    if not leftovers:
        return Result(True, "zero unresolved placeholders")
    return Result(False, f"unresolved: {', '.join(leftovers[:6])}{'…' if len(leftovers) > 6 else ''}")

def _c1_4(ctx: Ctx) -> Result:
    sz = len(ctx.html)
    return Result(sz >= 200_000, f"{sz:,} bytes")

def _c1_5(ctx: Ctx) -> Result:
    # Informational heuristic. Real parse validation is done externally by
    # `node --check` when available. Naive string-stripping cannot reliably
    # handle template literals containing `${}` or regex literals, so we
    # keep this as informational to avoid false positives.
    #
    # Windows deadlock fix: subprocess.run(timeout=N) uses communicate() which
    # joins reader threads — on Windows those threads can block indefinitely on
    # large stdout/stderr pipes even after the process exits (Python issue
    # #87512). We use Popen + a threading.Timer hard-kill instead, which is
    # immune to the thread-join deadlock.
    import shutil
    node = shutil.which("node")
    if not node:
        return Result(True, "node not installed — skipping parse check")
    import subprocess, tempfile, os as _os, threading
    m = list(re.finditer(r'<script[^>]*>([\s\S]*?)</script>', ctx.html))
    if not m:
        return Result(False, "no <script> blocks found")
    body = m[-1].group(1)
    # Skip the check when the script block is very large (> 1 MB) — node
    # --check on a 3 MB inline script can take 30+ seconds even when the
    # syntax is valid, because the V8 parser has to tokenise the whole
    # string. This is purely an informational/warn-level check so skipping
    # it for oversized bundles does not affect the error count.
    MAX_SCRIPT_BYTES = 1_000_000  # 1 MB
    if len(body.encode("utf-8", errors="replace")) > MAX_SCRIPT_BYTES:
        return Result(True, f"node check skipped: script block too large ({len(body):,} chars)")
    fd, path = tempfile.mkstemp(suffix=".js")
    try:
        with _os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(body)
        TIMEOUT = 20  # seconds
        proc = subprocess.Popen([node, "--check", path],
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        timed_out = [False]
        def _kill():
            timed_out[0] = True
            try: proc.kill()
            except Exception: pass
        timer = threading.Timer(TIMEOUT, _kill)
        try:
            timer.start()
            stdout_b, stderr_b = proc.communicate()
        finally:
            timer.cancel()
        if timed_out[0]:
            return Result(True, f"node check skipped: timed out after {TIMEOUT}s")
        stdout_s = stdout_b.decode("utf-8", errors="replace")
        stderr_s = stderr_b.decode("utf-8", errors="replace")
        return Result(proc.returncode == 0,
                      "node --check passed" if proc.returncode == 0
                      else (stderr_s or stdout_s).splitlines()[0][:200])
    except Exception as e:
        return Result(True, f"node check skipped: {e!r}")
    finally:
        try: _os.unlink(path)
        except Exception: pass

